/** Review captures are opt-in and written to SHOTS_DIR, outside the repository. */
import { test, expect } from "@playwright/test";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createHash } from "node:crypto";
const enabled = process.env.REVIEW_EXPLORER === "1";
const url = process.env.REVIEW_URL ?? "http://127.0.0.1:8766";
const shots = process.env.SHOTS_DIR;
test("read-only review explorer visual states", async ({ page }) => {
  test.skip(true, "D-067 replaces this interface; use the review-d067 project");
  test.skip(!enabled, "REVIEW_EXPLORER=1 required");
  if (!shots) throw new Error("SHOTS_DIR is required");
  const target = resolve(shots), repo = resolve("..");
  if (target === repo || target.startsWith(repo + "/")) throw new Error("SHOTS_DIR must be outside the repository");
  await mkdir(target, { recursive: true });
  const consoleErrors: string[] = [], remoteRequests: string[] = [];
  page.on("console", (message) => { if (message.type() === "error") consoleErrors.push(message.text()); });
  page.on("pageerror", (error) => consoleErrors.push(error.message));
  page.on("request", (request) => { const host = new URL(request.url()).hostname; if (host !== "127.0.0.1" && host !== "localhost") remoteRequests.push(request.url()); });
  const timings: Record<string, number> = {};
  const navigationStart = performance.now(); await page.goto(url);
  await expect(page.locator("#status")).toContainText("Grafo pronto");
  timings.navigationToReady2dMs = Math.round(performance.now() - navigationStart);
  await page.screenshot({ path: resolve(target, "01-2d-overview.png") });
  const switchStart = performance.now();
  await page.locator("#view-3d").click();
  await expect(page.locator("#status")).toContainText("Grafo pronto · 3D");
  timings.switch2dTo3dMs = Math.round(performance.now() - switchStart);
  await page.goto("about:blank");
  const navigation3dStart = performance.now(); await page.goto(`${url}/#3d`);
  await expect(page.locator("#status")).toContainText("Grafo pronto · 3D");
  timings.navigationToReady3dMs = Math.round(performance.now() - navigation3dStart);
  await page.waitForTimeout(600);
  await page.screenshot({ path: resolve(target, "02-3d-overview.png") });
  const box = await page.locator("#viewport canvas").boundingBox(); if (!box) throw new Error("3D canvas missing");
  await page.mouse.move(box.x + box.width * .5, box.y + box.height * .5);
  const framesBefore = await page.evaluate(() => (window as typeof window & { __review: { renderedFrames(): number } }).__review.renderedFrames());
  await page.mouse.down();
  for (let step = 1; step <= 20; step++) { await page.mouse.move(box.x + box.width * (.5 + .18 * step / 20), box.y + box.height * (.5 + .08 * step / 20)); await page.waitForTimeout(100); }
  await page.mouse.up();
  timings.orbitFrames2s = await page.evaluate(() => (window as typeof window & { __review: { renderedFrames(): number } }).__review.renderedFrames()) - framesBefore;
  await page.waitForTimeout(600);
  await page.screenshot({ path: resolve(target, "03-3d-orbit.png") });
  const hash = (value: Buffer) => createHash("sha256").update(value).digest("hex");
  expect(hash(await readFile(resolve(target, "02-3d-overview.png")))).not.toBe(hash(await readFile(resolve(target, "03-3d-orbit.png"))));
  await page.locator("#search").fill("connection:"); await page.locator("#search-form button").click();
  await expect(page.locator("#details h2")).toBeVisible();
  await page.screenshot({ path: resolve(target, "04-connection-details.png") });
  await page.locator("#filter-class").selectOption("A");
  await page.screenshot({ path: resolve(target, "05-class-a.png") });
  const filtered = await page.evaluate(() => (window as typeof window & { __review: { visibleCounts(): {nodes:number; connectionClasses: Record<string, number>} } }).__review.visibleCounts());
  expect(filtered.nodes).toBeGreaterThan(0); expect(filtered.connectionClasses.A).toBeGreaterThan(0);
  expect([filtered.connectionClasses.B, filtered.connectionClasses.C, filtered.connectionClasses.D]).toEqual([0, 0, 0]);
  await page.locator("#filter-class").selectOption("");
  const response = await page.request.get(`${url}/api/export.json`); const graph = await response.json() as { nodes: {id:string;type:string;label:string}[]; edges: {type:string;source:string;target:string}[] };
  const focus = graph.nodes.find((node) => node.type === "connection" && ["Quillmap", "Orchardline", "Atlasfield", "ATLASvault"].every((name) => graph.edges.some((edge) => edge.type === "links" && edge.source === node.id && edge.target === `domain:${name}`)));
  expect(focus).toBeDefined(); await page.locator("#search").fill(focus!.id); await page.locator("#search-form button").click();
  await page.waitForTimeout(1500);
  await expect.poll(() => page.evaluate(() => (window as typeof window & { __review: { cameraPosition(): { settled: boolean } | null } }).__review.cameraPosition()?.settled), { timeout: 5000 }).toBe(true);
  for (const domain of graph.edges.filter((edge) => edge.type === "links" && edge.source === focus!.id).map((edge) => graph.nodes.find((node) => node.id === edge.target)).filter((node): node is typeof graph.nodes[number] => node !== undefined)) {
    await expect(page.locator("#viewport .space-label").filter({ hasText: new RegExp(`^${domain.label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}$`) })).toBeVisible();
  }
  await page.screenshot({ path: resolve(target, "06-quillmap-connection.png") });
  const spread = await page.evaluate(() => (window as typeof window & { __review: { depthStats(): {x:{std:number};y:{std:number};z:{min:number;max:number;std:number}} } }).__review.depthStats());
  expect(spread.z.max - spread.z.min).toBeGreaterThan(1.5);
  expect(spread.z.std).toBeGreaterThan(Math.min(spread.x.std, spread.y.std) * .5);
  const reverseStart = performance.now(); await page.locator("#view-2d").click(); await expect(page.locator("#status")).toContainText("Grafo pronto · 2D");
  timings.switch3dTo2dMs = Math.round(performance.now() - reverseStart);
  await writeFile(resolve(target, "timings.json"), JSON.stringify(timings, null, 2) + "\n");
  expect(consoleErrors).toEqual([]); expect(remoteRequests).toEqual([]);
});

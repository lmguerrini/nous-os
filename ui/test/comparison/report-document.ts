/**
 * Generates the CAP-14 comparison report from its two evidence artifacts.
 *
 * This is deliberately a consumer of the artifacts, not a second comparison
 * analysis. Numeric claims are rendered only from their recorded values and
 * every source figure retains the configuration that produced it.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import type {
  ComparisonAnalysis,
  ComparisonRecord,
  ComparisonScaleEvidence,
  SourceConfiguration,
  SourceMeasurementEvidence,
} from "#comparison/analyse.ts";
import type { PerformanceRecord, PerformanceResult, PerformanceScale } from "#browser/performance-contract.ts";

const COMPARISON_PATH = ["dist", "evidence", "comparison.json"].join("/");
const PERFORMANCE_PATH = ["dist", "evidence", "performance.json"].join("/");
const DOCUMENT_PATH = ["..", "docs", "CAP-14-COMPARISON.md"].join("/");

const GOVERNED_OUTCOMES = new Set([
  "MEASURED",
  "NOT_COMPARABLE",
  "NOT_RUN",
  "SCALE_DEPENDENT",
  "NO_MATERIAL_DIFFERENCE",
  "MATERIAL",
]);

const comparison = await readArtifact<ComparisonAnalysis>(COMPARISON_PATH, "npm run evidence:comparison");
const performance = await readArtifact<PerformanceResult>(PERFORMANCE_PATH, "npm run test:performance");

assertArtifactBinding(comparison, performance);
await mkdir(["..", "docs"].join("/"), { recursive: true });
await writeFile(DOCUMENT_PATH, renderDocument(comparison, performance));
process.stdout.write("CAP-14-COMPARISON.md written from comparison.json and performance.json\n");

async function readArtifact<Artifact>(path: string, producer: string): Promise<Artifact> {
  try {
    return JSON.parse(await readFile(path, "utf8")) as Artifact;
  } catch (error: unknown) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`${path} is absent or unreadable; run \`${producer}\` first. ${detail}`);
  }
}

function renderDocument(analysis: ComparisonAnalysis, source: PerformanceResult): string {
  const scales = scaleFacts(source.records);
  const sections = (["projection", "renderer"] as const).map((kind) => renderContrast(
    kind,
    analysis.comparisons.filter((record) => record.kind === kind),
    source.records,
    scales,
  ));
  return `${[
    "# CAP-14 renderer comparison",
    "",
    "<!-- Generated by `npm --prefix ui run report:comparison` from `dist/evidence/comparison.json` and `dist/evidence/performance.json`. Do not edit figures by hand. -->",
    "",
    "## Scope and limits",
    "",
    `Synthetic-fixture declaration: ${source.syntheticFixtureDeclaration}`,
    "",
    "Human cognition: `NOT_TESTED`. No figure in this report tests or permits an inference about human cognition.",
    "",
    "CAP-14 decides nothing about shipping and expresses no preference for either projection.",
    "",
    "## Contrasts",
    "",
    ...sections,
  ].join("\n")}\n`;
}

function renderContrast(
  kind: "projection" | "renderer",
  comparisons: readonly ComparisonRecord[],
  records: readonly PerformanceRecord[],
  scales: ReadonlyMap<PerformanceScale, ScaleFacts>,
): string {
  if (comparisons.length === 0) {
    throw new Error(`comparison artifact records no ${kind} contrast`);
  }
  const arms = comparisons[0]?.arms;
  if (arms === undefined || comparisons.some((record) => record.arms.first !== arms.first || record.arms.second !== arms.second)) {
    throw new Error(`${kind} comparison records do not agree on their arms`);
  }
  const heading = kind === "projection"
    ? `### Projection contrast — ${arms.first} vs ${arms.second}`
    : `### Renderer comparison — ${arms.first} vs ${arms.second}`;
  const control = kind === "projection"
    ? "Same renderer; projection is the only variable. This is the only contrast that supports a 2D-vs-3D statement."
    : "Renderer varies while projection is held at 2D. This is a renderer comparison, not a projection or 2D-vs-3D result.";
  return [
    heading,
    "",
    control,
    "",
    ...comparisons.flatMap((record) => [renderComparison(record, records, scales), ""]),
  ].join("\n");
}

function renderComparison(
  record: ComparisonRecord,
  records: readonly PerformanceRecord[],
  scales: ReadonlyMap<PerformanceScale, ScaleFacts>,
): string {
  const dimension = [
    `#### ${record.dimension}`,
    "",
    `Metric definition: ${record.metricDefinition}`,
    "",
    `Outcome: \`${governedOutcome(record.outcome)}\``,
    "",
    `Reason (instrument wording): ${record.reason}`,
    "",
  ];
  for (const scale of record.scales) {
    dimension.push(...renderScale(record, scale, records, scales), "");
  }
  return dimension.join("\n");
}

function renderScale(
  record: ComparisonRecord,
  scale: ComparisonScaleEvidence,
  records: readonly PerformanceRecord[],
  scales: ReadonlyMap<PerformanceScale, ScaleFacts>,
): readonly string[] {
  const facts = scaleFactsFor(scale.scale, scales);
  return [
    `##### Scale ${formatScale(facts)}`,
    "",
    ...renderSourceEvidence(record, scale.first, records, scales),
    "",
    ...renderSourceEvidence(record, scale.second, records, scales),
    ...(scale.ratio === null ? [] : [
      "",
      ...renderComparisonFigure(scale, scales),
    ]),
  ];
}

function renderSourceEvidence(
  record: ComparisonRecord,
  evidence: SourceMeasurementEvidence,
  records: readonly PerformanceRecord[],
  scales: ReadonlyMap<PerformanceScale, ScaleFacts>,
): readonly string[] {
  const configuration = evidence.provenance.configuration;
  const sourceRecord = findSourceRecord(records, configuration);
  assertConfigurationMatchesRecord(configuration, sourceRecord, record.dimension);
  const facts = scaleFactsFor(configuration.scale, scales);
  const label = evidence.medianMs === null ? "Measurement availability" : "Evidence figure";
  const status = sourceOutcome(evidence);
  return [
    `###### ${label} — ${configuration.arm} at ${formatScale(facts)}`,
    "",
    `- Outcome: \`${status}\``,
    ...(evidence.medianMs === null ? [] : [`- Median: \`${String(evidence.medianMs)} ms\``]),
    ...(evidence.reason === null ? [] : [`- Reason (instrument wording): ${evidence.reason}`]),
    `- Command: \`${evidence.provenance.command}\``,
    `- Fixture: \`${configuration.fixture ?? "NOT_RUN"}\``,
    `- Arm: \`${configuration.arm}\``,
    `- Scale: ${formatScale(facts)}`,
    `- Configuration: viewport \`${formatViewport(configuration)}\`; warm-up frames excluded: \`${String(configuration.warmupFramesExcluded ?? "NOT_RUN")}\`.`,
    `- Caveat: \`${evidence.provenance.caveat}\``,
  ];
}

function renderComparisonFigure(
  scale: ComparisonScaleEvidence,
  scales: ReadonlyMap<PerformanceScale, ScaleFacts>,
): readonly string[] {
  const provenance = scale.comparisonProvenance;
  if (provenance === null) {
    throw new Error(`comparison figure at ${scale.scale} has a ratio without provenance`);
  }
  return [
    `###### Comparison figure — ${formatScale(scaleFactsFor(scale.scale, scales))}`,
    "",
    `- Ratio: \`${String(scale.ratio)}\``,
    `- Direction: \`${String(scale.direction)}\``,
    `- Command: \`${provenance.command}\``,
    ...provenance.configurations.flatMap((configuration) => [
      `- Fixture: \`${configuration.fixture ?? "NOT_RUN"}\`; arm: \`${configuration.arm}\`; scale: ${formatScale(scaleFactsFor(configuration.scale, scales))}; configuration: viewport \`${formatViewport(configuration)}\`, warm-up frames excluded \`${String(configuration.warmupFramesExcluded ?? "NOT_RUN")}\`.`,
    ]),
    `- Caveat: \`${provenance.caveat}\``,
  ];
}

type ScaleFacts = {
  readonly scale: PerformanceScale;
  readonly nodes: number | "NOT_RUN";
  readonly edges: number | "NOT_RUN";
};

function scaleFacts(records: readonly PerformanceRecord[]): ReadonlyMap<PerformanceScale, ScaleFacts> {
  const facts = new Map<PerformanceScale, ScaleFacts>();
  for (const record of records) {
    const candidate: ScaleFacts = {
      scale: record.scale,
      nodes: record.elementCounts.fixtureNodes,
      edges: record.elementCounts.fixtureEdges,
    };
    const existing = facts.get(record.scale);
    if (existing === undefined) {
      facts.set(record.scale, candidate);
      continue;
    }
    if (existing.nodes !== candidate.nodes || existing.edges !== candidate.edges) {
      throw new Error(
        `performance artifact disagrees about fixture counts at ${record.scale}: `
        + `${String(existing.nodes)}/${String(existing.edges)} versus ${String(candidate.nodes)}/${String(candidate.edges)}`,
      );
    }
  }
  return facts;
}

function scaleFactsFor(scale: PerformanceScale, facts: ReadonlyMap<PerformanceScale, ScaleFacts>): ScaleFacts {
  const scaleFacts = facts.get(scale);
  if (scaleFacts === undefined) {
    throw new Error(`performance artifact records no fixture counts for ${scale}`);
  }
  return scaleFacts;
}

function formatScale(facts: ScaleFacts): string {
  const counts = facts.nodes === "NOT_RUN" || facts.edges === "NOT_RUN"
    ? `nodes ${String(facts.nodes)} and edges ${String(facts.edges)}`
    : `${String(facts.nodes)} nodes and ${String(facts.edges)} edges`;
  return `\`${facts.scale}\` (${counts})`;
}

function formatViewport(configuration: SourceConfiguration): string {
  const viewport = configuration.viewport;
  return viewport === null ? "NOT_RUN" : `${String(viewport.width)} × ${String(viewport.height)}`;
}

function sourceOutcome(evidence: SourceMeasurementEvidence): string {
  switch (evidence.status) {
    case "PASS":
      return governedOutcome("MEASURED");
    case "NOT_RUN":
      return governedOutcome("NOT_RUN");
    case "UNKNOWN":
    case "MISSING":
      return governedOutcome("NOT_COMPARABLE");
  }
}

function governedOutcome(outcome: string): string {
  if (!GOVERNED_OUTCOMES.has(outcome)) {
    throw new Error(`comparison artifact uses an ungoverned outcome ${outcome}`);
  }
  return outcome;
}

function findSourceRecord(records: readonly PerformanceRecord[], configuration: SourceConfiguration): PerformanceRecord {
  const record = records.find((candidate) => candidate.renderer === configuration.arm && candidate.scale === configuration.scale);
  if (record === undefined) {
    throw new Error(`comparison provenance references missing performance record ${configuration.arm} at ${configuration.scale}`);
  }
  return record;
}

function assertConfigurationMatchesRecord(
  configuration: SourceConfiguration,
  record: PerformanceRecord,
  dimension: string,
): void {
  const viewportMatches = configuration.viewport !== null
    && configuration.viewport.width === record.viewport.width
    && configuration.viewport.height === record.viewport.height;
  if (
    configuration.fixture !== record.fixture
    || !viewportMatches
    || configuration.warmupFramesExcluded !== record.warmup.framesExcluded
  ) {
    throw new Error(
      `comparison provenance for ${dimension} at ${configuration.arm}/${configuration.scale} does not match performance.json`,
    );
  }
}

function assertArtifactBinding(analysis: ComparisonAnalysis, source: PerformanceResult): void {
  if (analysis.source.observedCommitSha !== source.observedCommitSha) {
    throw new Error(
      `comparison artifact is bound to ${analysis.source.observedCommitSha}, but performance artifact is bound to ${source.observedCommitSha}`,
    );
  }
  if (analysis.source.caveat !== source.rasterisationLabel) {
    throw new Error("comparison and performance artifacts disagree about the rasterisation caveat");
  }
}
